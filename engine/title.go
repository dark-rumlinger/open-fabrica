package engine

// Auto-titling: when a project was created with an auto-minted adjective-noun
// name, the engine asks the LLM for a description-derived title before the
// first stage runs. Owner-typed names are never touched; the domain/slug stays
// as-is so routing keeps working. Best-effort: failure never blocks the build.

import (
	"context"
	"strings"
	"time"

	"openfabrica/db/models"
	"openfabrica/events"
	"openfabrica/providers/llm"
)

const (
	maxGeneratedTitleLen = 60
	titleGenTimeout      = 30 * time.Second
	reactionGenTimeout   = 15 * time.Second
	// maxTitleAttempts bounds the collision-retry loop. The taken-name set is
	// fed into the FIRST call and each call returns several candidates, so a
	// retry only fires on the race where a name is taken between the list
	// read and the check.
	maxTitleAttempts = 2
)

const titleSystemPrompt = "You name software projects. Given a project description, reply with THREE distinct candidate titles, one per line, each a distinctive 2 to 4 word title in Title Case. " +
	"Order them most-specific first: put the candidate that most clearly points at THIS project's subject on line one. " +
	"Each title must make the project's subject clear: anchor it to the concrete thing the project is about - its domain, its content, or its core action - so someone reading only the name can tell roughly what it does. " +
	"Aim for memorable but specific: a vivid, on-topic noun phrase or light wordplay that still points at the subject. " +
	"Do NOT produce vague, abstract, or mood-only names that could belong to any project. Avoid generic templated names and the usual filler suffixes (Hub, Flow, Pro, Studio, Lab, App, ...ify). " +
	"Examples of the right specificity. A birdsong identifier: 'Warbler Watch' or 'BirdSong ID', not 'NatureFlow' or 'EchoSpace'. " +
	"A used-textbook marketplace: 'Campus Bookswap' or 'Dorm Shelf', not 'PageHub' or 'BrightExchange'. " +
	"A marathon training planner: 'Mile Ladder' or 'Race Day Ready', not 'RunPro' or 'MomentumFlow'. " +
	"No numbering, no bullets, no quotes, no surrounding punctuation, no trailing periods, no explanation."

const reactionSystemPrompt = "You are an upbeat builder about to start someone's software project. Given the project description, reply with ONE short, warm sentence (max 12 words) reacting to what the idea actually is. Be specific to the idea, not generic. Do NOT name the project. No quotes, no emoji, no dashes, no lists, no explanation."

// maybeGenerateTitle replaces an auto-minted project name with an LLM-derived
// title. Called once at the start of a fresh build run.
func (w *Worker) maybeGenerateTitle(ctx context.Context) {
	project, err := models.GetProjectByID(w.deps.DB.DB, w.projectID)
	if err != nil || project == nil {
		return
	}
	if !models.ProjectNameIsAutoGenerated(project) {
		return // never touch a name the owner typed
	}
	desc := ""
	if project.Description != nil {
		desc = strings.TrimSpace(*project.Description)
	}
	if desc == "" {
		return // nothing to base a title on
	}

	taken, _ := models.ListProjectNames(w.deps.DB.DB)
	var title string
	for attempt := 0; attempt < maxTitleAttempts; attempt++ {
		candidates, err := w.titleCompletion(ctx, titleSystemPrompt, titleUserMsg(desc, taken), 48, titleGenTimeout)
		if err != nil {
			w.logger.Warn("title generation failed, keeping auto-minted name", "error", err)
			return
		}
		for _, candidate := range parseTitleCandidates(candidates) {
			if strings.EqualFold(candidate, project.Name) {
				continue
			}
			if exists, _ := models.ProjectNameExists(w.deps.DB.DB, candidate); exists {
				taken = append(taken, candidate)
				continue
			}
			title = candidate
			break
		}
		if title != "" {
			break
		}
	}
	if title == "" {
		// Every attempt collided. Keep the minted name but clear the flag so
		// we don't retry on every rebuild.
		w.logger.Info("all generated titles already in use, keeping current name")
		_ = models.SetProjectNameAutoGenerated(w.deps.DB.DB, w.projectID, false)
		return
	}

	if err := models.UpdateProjectName(w.deps.DB.DB, w.projectID, title); err != nil {
		w.logger.Warn("failed to persist generated title", "error", err)
		return
	}
	_ = models.SetProjectNameAutoGenerated(w.deps.DB.DB, w.projectID, false)

	// Live-update the admin UI: the project header animates the rename and
	// the project list refreshes off the same event.
	w.publishEvent(events.EventProjectUpdated, map[string]any{
		"name":    title,
		"animate": true,
	})
	w.publishMessage(w.titleAnnouncement(ctx, desc, title))
	w.logger.Info("generated project title", "title", title)
}

// maxAvoidNames bounds the taken names the title prompt lists. Every candidate is
// checked against the database anyway, so the list is only a steer; uncapped it grew
// with every project on the instance. The tail is kept: a retry appends the
// candidates that just collided, which are the most useful to avoid.
const maxAvoidNames = 40

func titleUserMsg(desc string, avoid []string) string {
	msg := "Project description:\n" + desc
	if len(avoid) > maxAvoidNames {
		avoid = avoid[len(avoid)-maxAvoidNames:]
	}
	if len(avoid) > 0 {
		msg += "\n\nThese names are already taken, every candidate must be clearly different from all of them: " + strings.Join(avoid, ", ")
	}
	return msg
}

// titleCompletion runs one short, non-thinking completion through the
// engine's standard call path (limiter, logging; replay cache skipped - the
// call is creative and cheap).
func (w *Worker) titleCompletion(ctx context.Context, system, userMsg string, maxTokens int, timeout time.Duration) (string, error) {
	src := w.providerSrc()
	rp, err := src.resolve()
	if err != nil {
		return "", err
	}
	fallback := src.fallbackHook()

	caller := &llmCaller{limiter: w.limiter, pdb: w.pdb, dbLog: w.dbLog, logger: w.logger, budgetFn: w.deps.DailyTokenBudgetFn}
	noThink := false
	// Higher temperature than the build stages on purpose: naming is a
	// creative task and a wider distribution yields less templated titles.
	temp := 0.8
	runID := ""
	if w.run != nil {
		runID = w.run.ID
	}
	resp, _, _, err := caller.call(ctx, callParams{
		rp: rp,
		req: llm.CompletionRequest{
			Model:       rp.Model,
			System:      system,
			Messages:    []llm.Message{{Role: llm.RoleUser, Content: userMsg}},
			MaxTokens:   maxTokens,
			Temperature: &temp,
			Thinking:    &noThink,
			// One-shot call outside the session loop, so there is no cached prefix to report.
			// The total is still worth recording: the cost views skip rows that leave it zero.
			TotalRequestBytes: len(system) + len(userMsg),
		},
		policy:        policyLive,
		timeout:       timeout,
		fallback:      fallback,
		stage:         "title",
		runID:         runID,
		noReplayCache: true,
	})
	if err != nil {
		return "", err
	}
	return resp.Content, nil
}

// parseTitleCandidates splits a multi-line completion into sanitized
// candidates, dropping empties and stray list markers.
func parseTitleCandidates(content string) []string {
	var out []string
	for _, line := range strings.Split(content, "\n") {
		line = strings.TrimSpace(line)
		line = strings.TrimLeft(line, "-*0123456789.) \t")
		if c := sanitizeTitle(line); c != "" {
			out = append(out, c)
		}
	}
	return out
}

// titleAnnouncement pairs an idea-specific opener (best-effort LLM) with a
// varied naming clause; falls back to a pooled opener so the announcement is
// always lively and never blocks on the model.
func (w *Worker) titleAnnouncement(ctx context.Context, desc, title string) string {
	reactionRaw, err := w.titleCompletion(ctx, reactionSystemPrompt, "Project description:\n"+desc, 32, reactionGenTimeout)
	if err == nil {
		if reaction := sanitizeReaction(reactionRaw); reaction != "" {
			// The reaction is the model's own sentence; the naming line is ours, so it
			// is translated here rather than as part of the joined message.
			naming := w.tr(pickPhrase(
				"Calling it **%s**. Let's build.",
				"**%s** it is. Building now.",
				"I'll call it **%s**. Here we go.",
			), title)
			return reaction + " " + naming
		}
	}
	return w.tr(pickPhrase(
		"Love it. I'm calling this one **%s**. Let's build it.",
		"**%s** it is. Let's get building.",
		"Going with **%s**. Let's build it.",
	), title)
}

// sanitizeReaction trims the model's reply to one clean sentence: first line
// only, stripped of wrapping quotes/markdown, stray dashes removed.
func sanitizeReaction(s string) string {
	s = strings.TrimSpace(s)
	if i := strings.IndexAny(s, "\r\n"); i >= 0 {
		s = s[:i]
	}
	s = strings.Trim(s, " \t\"'`*#")
	s = strings.ReplaceAll(s, "—", " ")
	s = strings.ReplaceAll(s, "–", " ")
	return strings.Join(strings.Fields(s), " ")
}

// sanitizeTitle trims the model's reply to a single clean line, capped.
func sanitizeTitle(s string) string {
	s = strings.TrimSpace(s)
	if i := strings.IndexAny(s, "\r\n"); i >= 0 {
		s = s[:i]
	}
	s = strings.Trim(s, " \t\"'`.*#")
	if len(s) > maxGeneratedTitleLen {
		s = strings.TrimSpace(s[:maxGeneratedTitleLen])
	}
	return s
}
