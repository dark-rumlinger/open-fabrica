// projectConfigTestSchema is the minimal projects table the config helpers touch.
const projectConfigTestSchema = `
CREATE TABLE projects (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT, domain TEXT, description TEXT, llm_model_id INTEGER,
  published INTEGER, mode TEXT, config TEXT NOT NULL DEFAULT '', source_project_id INTEGER,
  ambition_level TEXT,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);`

func newProjectConfigDB(t *testing.T) (*sql.DB, int) {
	t.Helper()
	db, err := sql.Open("sqlite", ":memory:")
	if err != nil {
		t.Fatalf("open: %v", err)
	}
	t.Cleanup(func() { _ = db.Close() })
	if _, err := db.Exec(projectConfigTestSchema); err != nil {
		t.Fatalf("schema: %v", err)
	}
	res, err := db.Exec("INSERT INTO projects (name, published, mode, llm_model_id, ambition_level) VALUES ('p',1,'building',1,'standard')")
	if err != nil {
		t.Fatalf("insert: %v", err)
	}
	id, _ := res.LastInsertId()
	return db, int(id)
}

// The deploy policy decides whether a build that is broken on arrival may reach a
// user, so an unset override must read as "" (meaning: use the platform default)
// rather than as any policy in particular, and a set one must survive a round trip.
func TestProjectDeployPolicyRoundTrip(t *testing.T) {
	db, id := newProjectConfigDB(t)

	p, err := GetProjectByID(db, id)
	if err != nil {
		t.Fatalf("get: %v", err)
	}
	if got := ProjectDeployPolicy(p); got != "" {
		t.Errorf("unset deploy policy = %q, want %q (the engine owns the default)", got, "")
	}

	if err := SetProjectDeployPolicy(db, id, "strict"); err != nil {
		t.Fatalf("set deploy policy: %v", err)
	}
	if p, err = GetProjectByID(db, id); err != nil {
		t.Fatalf("get: %v", err)
	}
	if got := ProjectDeployPolicy(p); got != "strict" {
		t.Errorf("deploy policy = %q, want %q", got, "strict")
	}

	// Clearing restores "use the platform default" rather than pinning the value
	// the default happened to have when it was cleared.
	if err := SetProjectDeployPolicy(db, id, ""); err != nil {
		t.Fatalf("clear deploy policy: %v", err)
	}
	if p, err = GetProjectByID(db, id); err != nil {
		t.Fatalf("get: %v", err)
	}
	if got := ProjectDeployPolicy(p); got != "" {
		t.Errorf("cleared deploy policy = %q, want %q", got, "")
	}
}

// TestMutateProjectConfigPreservesOtherKeys: setting one config key must not drop
// the others already stored in the blob.
func TestMutateProjectConfigPreservesOtherKeys(t *testing.T) {
	db, id := newProjectConfigDB(t)

	if err := SetProjectBannedIPs(db, id, []string{"203.0.113.0/24"}); err != nil {
		t.Fatalf("set banned ips: %v", err)
	}
	if err := SetProjectCSP(db, id, "default-src 'self'"); err != nil {
		t.Fatalf("set csp: %v", err)
	}
	if err := SetProjectNameAutoGenerated(db, id, true); err != nil {
		t.Fatalf("set auto-name: %v", err)
	}
	if err := SetProjectDeployPolicy(db, id, "strict"); err != nil {
		t.Fatalf("set deploy policy: %v", err)
	}

	p, err := GetProjectByID(db, id)
	if err != nil {
		t.Fatalf("get: %v", err)
	}
	if got := ProjectBannedIPs(p); len(got) != 1 || got[0] != "203.0.113.0/24" {
		t.Errorf("banned IPs lost after later writes: %v", got)
	}
	if got := ProjectCSP(p); got != "default-src 'self'" {
		t.Errorf("CSP lost after later writes: %q", got)
	}
	if !ProjectNameIsAutoGenerated(p) {
		t.Error("auto-name flag lost after later writes")
	}
	if got := ProjectDeployPolicy(p); got != "strict" {
		t.Errorf("deploy policy lost after later writes: %q", got)
	}
}

// TestMutateProjectConfigRejectsCorruptBlob: a non-empty but unparseable config
// blob must produce an error, not a silent wholesale overwrite that discards
// whatever the corrupt blob may have held.
func TestMutateProjectConfigRejectsCorruptBlob(t *testing.T) {
	db, id := newProjectConfigDB(t)
	if _, err := db.Exec("UPDATE projects SET config = ? WHERE id = ?", "{not valid json", id); err != nil {
		t.Fatalf("seed corrupt: %v", err)
	}

	err := SetProjectCSP(db, id, "default-src 'self'")
	if err == nil {
		t.Fatal("expected error on corrupt config blob, got nil (silent overwrite)")
	}
	if !strings.Contains(err.Error(), "unparseable config") {
		t.Errorf("unexpected error: %v", err)
	}

	// The corrupt blob must be left untouched, not overwritten.
	var cfg string
	if err := db.QueryRow("SELECT config FROM projects WHERE id = ?", id).Scan(&cfg); err != nil {
		t.Fatalf("read back: %v", err)
	}
	if cfg != "{not valid json" {
		t.Errorf("corrupt blob was modified: %q", cfg)
	}
}

// Publishing is a flag of its own: it decides who is served and which projects
// the engine, jobs and TLS proxy work on, and it never touches the mode.
func TestPublishedFlagAndListing(t *testing.T) {
	db, id := newProjectConfigDB(t)

	p, err := GetProjectByID(db, id)
	if err != nil {
		t.Fatal(err)
	}
	if !p.Published {
		t.Fatal("fixture project should start published")
	}
	if list, err := ListPublishedProjects(db); err != nil || len(list) != 1 {
		t.Fatalf("published list = %d, %v, want the one project", len(list), err)
	}

	if err := SetProjectPublished(db, id, false); err != nil {
		t.Fatal(err)
	}
	p, _ = GetProjectByID(db, id)
	if p.Published || p.Mode != ModeBuilding {
		t.Errorf("after unpublishing: published=%v mode=%q, want unpublished and mode untouched", p.Published, p.Mode)
	}
	if list, _ := ListPublishedProjects(db); len(list) != 0 {
		t.Errorf("unpublished project still listed: %d", len(list))
	}
}

// Publishing does not decide which projects run background work. The only
// project held back is one that is both unpublished and paused, which is what an
// import lands as until the owner has reviewed it.
func TestRunnableProjectsIgnorePublishing(t *testing.T) {
	db, _ := newProjectConfigDB(t)
	for _, row := range []struct {
		name      string
		published int
		mode      string
	}{
		{"published-paused", 1, ModePaused},
		{"hidden-building", 0, ModeBuilding},
		{"hidden-live", 0, ModeLive},
		{"hidden-paused", 0, ModePaused},
	} {
		if _, err := db.Exec(
			"INSERT INTO projects (name, published, mode, llm_model_id, ambition_level) VALUES (?, ?, ?, 1, 'standard')",
			row.name, row.published, row.mode); err != nil {
			t.Fatal(err)
		}
	}

	list, err := ListRunnableProjects(db)
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]bool{}
	for _, p := range list {
		got[p.Name] = true
	}
	for _, want := range []string{"p", "published-paused", "hidden-building", "hidden-live"} {
		if !got[want] {
			t.Errorf("%s should be runnable, got %v", want, got)
		}
	}
	if got["hidden-paused"] {
		t.Error("an unpublished, paused project (an import awaiting review) must not start")
	}

	pub, _ := ListPublishedProjects(db)
	for _, p := range pub {
		if p.Name == "hidden-building" || p.Name == "hidden-live" || p.Name == "hidden-paused" {
			t.Errorf("%s is unpublished but listed as published", p.Name)
		}
	}
}

// User-flow tests are off unless the owner turned them on: an unset key, an unreadable
// blob and an explicit false all read as off. Either choice is stored explicitly and
// survives a round trip with the other config keys.
func TestProjectUserFlowsSetting(t *testing.T) {
	db, id := newProjectConfigDB(t)

	p, err := GetProjectByID(db, id)
	if err != nil {
		t.Fatalf("get: %v", err)
	}
	if ProjectUserFlowsEnabled(p) {
		t.Fatal("unset must read as off")
	}
	if ProjectUserFlowsEnabled(nil) || ProjectUserFlowsEnabled(&Project{Config: "{not json"}) {
		t.Fatal("a missing project or an unparseable blob must read as off")
	}

	if err := SetProjectCSP(db, id, "default-src 'self'"); err != nil {
		t.Fatalf("set csp: %v", err)
	}
	if err := SetProjectUserFlows(db, id, true); err != nil {
		t.Fatalf("turn on: %v", err)
	}
	p, _ = GetProjectByID(db, id)
	if !ProjectUserFlowsEnabled(p) {
		t.Fatal("turned on must read as on")
	}
	if ProjectCSP(p) != "default-src 'self'" {
		t.Errorf("turning flows on must keep the other keys, config = %q", p.Config)
	}

	if err := SetProjectUserFlows(db, id, false); err != nil {
		t.Fatalf("turn off: %v", err)
	}
	p, _ = GetProjectByID(db, id)
	if ProjectUserFlowsEnabled(p) || !strings.Contains(p.Config, "user_flows") {
		t.Errorf("turning off must store the explicit choice, config = %q", p.Config)
	}
}

// Concurrent setters each rewrite the whole config blob; without serialization two
// of them read the same old blob and the later write drops the earlier key.
func TestMutateProjectConfigConcurrentSettersKeepAllKeys(t *testing.T) {
	db, id := newProjectConfigDB(t)
	db.SetMaxOpenConns(1) // an in-memory database lives on one connection

	for round := 0; round < 20; round++ {
		var wg sync.WaitGroup
		for _, set := range []func() error{
			func() error { return SetProjectBannedIPs(db, id, []string{"203.0.113.0/24"}) },
			func() error { return SetProjectCSP(db, id, "default-src 'self'") },
			func() error { return SetProjectDeployPolicy(db, id, "strict") },
			func() error { return SetProjectNameAutoGenerated(db, id, true) },
		} {
			wg.Add(1)
			go func() {
				defer wg.Done()
				if err := set(); err != nil {
					t.Errorf("setter: %v", err)
				}
			}()
		}
		wg.Wait()

		p, err := GetProjectByID(db, id)
		if err != nil {
			t.Fatal(err)
		}
		if len(ProjectBannedIPs(p)) != 1 || ProjectCSP(p) == "" || ProjectDeployPolicy(p) != "strict" || !ProjectNameIsAutoGenerated(p) {
			t.Fatalf("round %d lost a key: %s", round, p.Config)
		}
	}
}
